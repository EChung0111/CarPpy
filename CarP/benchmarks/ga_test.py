import numpy as np
import matplotlib.pyplot as plt
import os
from scipy.cluster.hierarchy import dendrogram, linkage, cut_tree
import networkx as nx

from pathlib import Path
import sys
import shutil



path_root = Path(__file__).parents[2]
sys.path.append(str(path_root))

import CarP
from CarP.rmsd import rmsd_qcp
from CarP.ga_operations import *
from CarP import set_ring_pucker
import os

pwd = os.path.abspath('')
conf = CarP.Conformer(os.path.join(pwd,'glucose'))
conf.load_log(software='xyz')

cm = conf.connectivity_matrix()
cycles = (nx.cycle_basis(cm))

rd_list = conf.sort_ring_atoms(cycles, cm, conf)
print(rd_list)
Cspace = []

conf.ring_graph_maker(rd_list, cm)

stereo_dict = {}
for node, rd in enumerate(rd_list):
    conf.sugar_stero(rd)
    conf.glycosidic_link_type(rd)
    stereo_dict[node] = conf.stero

nx.set_node_attributes(conf.graph,stereo_dict,'absconf')

conf_int = conf

puckers = {  'Chair': ['1C4' ,  '4C1'],
                 'Boat' : ['1,4B', 'B1,4',  '2,5B', 'B2,5', '3,6B', 'B3,6'],
                 'Half' : ['1H2' ,  '2H1',  '2H3' ,  '3H2', '3H4' ,  '4H3',  '4H5' ,  '5H4',  '5H6' ,  '6H5',  '6H1' ,  '1H6'],
                 'Skew' : ['1S3' ,  '3S1',  '5S1' ,  '1S5',  '6S2' ,  '2S6'],
                 'Env'  : ['1E'  ,  'E1' ,  '2E'  ,  'E2' ,  '3E'  ,  'E3' ,  '4E'  ,  'E4' ,   '5E'  ,  'E5' ,  '6E'  ,  'E6' ]
                 }
puck_list = []
for key, val in zip(puckers.keys(), puckers.values()):

    for puck in val:

        print('\n\n',puck)
        puck_list.append(puck)
        set_ring_pucker(conf, 0, puck)
        xyz = conf.xyz.tolist()

        Cspace.append(xyz)
        conf = conf_int

rmsd = np.zeros((len(Cspace), len(Cspace)))
for i, conf1 in enumerate(Cspace):
    for j, conf2 in enumerate(Cspace):
        rmsd[i,j] = rmsd_qcp(conf1, conf2)

def cluster(Cspace, rmsd_mat):

    Z = CarP.linkage(rmsd_mat, 'single', optimal_ordering=True)

    fig = plt.figure(figsize=(6,4))
    dn = dendrogram (Z)
    fig.tight_layout()

    return fig

fig = cluster(Cspace, rmsd)
Cspace = np.array(Cspace)

np.savetxt('rmsd_mat.csv',rmsd,delimiter=',')
fig.savefig('cluster.png', dpi=300)

def save_Cspace(conf_int, Cspace, dir, puck_list):
    for puck, conf in zip(puck_list, Cspace):

        if os.path.exists(os.path.join(dir,f'conf_{puck}')) and os.path.isdir(os.path.join(dir,f'conf_{puck}')):
            shutil.rmtree(os.path.join(dir,f'conf_{puck}'))

        os.mkdir(os.path.join(dir,f"conf_{puck}"))

        with open(os.path.join(dir,f"conf_{puck}",'conf.xyz'),'w') as conf_file:

            atom_num = len(conf_int.atoms)
            conf_file.write(f"{atom_num}\n")
            conf_file.write("XYZ FILE GENERATED BY CARP\n")

            for row_num, row in enumerate(conf):
                atom_type = conf_int.atoms[row_num]
                atom_str_len = len(atom_type)

                gap_1 = 10
                gap_2 = 8
                gap_3 = 8
                gap_4 = 8

                if '-' in str(row[0]):
                    gap_1 -= 1

                if '-' in str(row[1]):
                    gap_2 -= 1

                if '-' in str(row[2]):
                    gap_3 -= 1

                gap_1 -= (atom_str_len + 1)

                gap_1 = " "*gap_1
                gap_2 = " "*gap_2
                gap_3 = " "*gap_3
                gap_4 = " "*gap_4\

                line = f"{atom_type}{gap_1}{row[0]:6f}{gap_2}{row[1]:6f}{gap_3}{row[2]:6f}{gap_4}\n"
                conf_file.write(line)

save_Cspace(conf_int, Cspace, 'glucose', puck_list)
